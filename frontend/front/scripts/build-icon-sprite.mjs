// Use the installed Phosphor shapes unchanged; only the regular weight is shipped.
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL, fileURLToPath } from 'node:url'
import { renderToStaticMarkup } from 'react-dom/server'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const names = [
  'ArrowRight',
  'ArrowLeft',
  'Check',
  'WarningCircle',
  'Info',
  'X',
  'House',
  'MapPin',
  'Books',
  'Lightbulb',
  'Plant',
  'SquaresFour',
  'Tray',
  'Intersect',
  'Bell',
  'UserCircle',
  'List',
  'CaretDown',
  'CaretUp',
  'MagnifyingGlass',
  'Clock',
  'Heart',
  'ChatCircle',
  'Users',
  'ClipboardText',
  'ShieldCheck',
  'ArrowSquareOut',
  'ArrowCounterClockwise',
  'SlidersHorizontal',
  'Plus',
  'CaretRight',
  'CheckCircle',
  'Cube',
  'Gear',
  'SignOut',
]
const symbols = []
for (const name of names) {
  const { default: weights } = await import(
    pathToFileURL(path.join(root, 'node_modules/@phosphor-icons/react/dist/defs', `${name}.es.js`))
  )
  symbols.push(
    `<symbol id="${name}" viewBox="0 0 256 256">${renderToStaticMarkup(weights.get('regular'))}</symbol>`,
  )
}
fs.writeFileSync(
  path.join(root, 'public/mbg-icons.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join('')}</svg>`,
)
fs.writeFileSync(
  path.join(root, 'src/components/iconNames.ts'),
  `// Generated by scripts/build-icon-sprite.mjs; Phosphor regular, MIT.\nexport const iconNames = ${JSON.stringify(names)} as const\nexport type IconName = typeof iconNames[number]\n`,
)
fs.copyFileSync(
  path.join(root, 'node_modules/@phosphor-icons/react/LICENSE'),
  path.join(root, 'public/brand/Phosphor-LICENSE.txt'),
)
